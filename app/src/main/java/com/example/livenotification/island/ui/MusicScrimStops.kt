package com.example.livenotification.island.ui

/**
 * 音乐锁屏「黑色渐变」的 stop 定义。
 *
 * ============ 为什么单独抽出来 ============
 *
 * 真机事故：`GradientDrawable.setColors(colors, offsets)` 要求**两个数组长度相等**，
 * 否则会在 **draw 的时候**抛
 *     java.lang.IllegalArgumentException: color and position arrays must be of equal length
 * 异常发生在绘制路径上，会直接把 SystemUI 打崩（不是一条日志那么简单）。
 * 我当时改了颜色项数却没同步 offsets 就踩了这个坑，而且编译期完全看不出来。
 *
 * 所以这对数组放在这里，由 `MusicScrimStopsTest` 守着：长度相等、
 * offset 单调递增且在 0..1、顶部要压暗、封面结束处必须不透明。
 */
object MusicScrimStops {

    /**
     * 渐变颜色（自上而下）。
     *
     * ============ 三段式设计 ============
     *
     * ① **顶部压暗**（0~38%）：系统锁屏时钟绘制在封面**之上**
     *    （KeyguardRootView 在音乐锁屏之上，这是我们刻意要的层级）。
     *    浅色封面 + 浅色时钟 = 看不清，所以顶部压一层黑。
     *    真机反馈："压暗封面亮度或者其他办法让时间能够更方便看"。
     *    这里用 0x8A(54%) → 0x59(35%) → 透明，只压时钟所在的那一段，
     *    中间留给封面本身。
     *
     * ② **中部保持干净**（38%~42% 完全透明）：让专辑封面保持可辨。
     *
     * ③ **封面结束处即完全不透明**（50% 起 #0F0F0F）：
     *    封面只铺到屏高 50%，封面以下露出的是锁屏壁纸。
     *    参考项目 MediaControlOverlay 的 0.70@35% 是给"封面铺满卡片"设计的，
     *    照搬会让壁纸透出一小条（真机确认）。
     */
    val COLORS = intArrayOf(
        0x8A000000.toInt(),   // 0.00 顶部压暗（时钟可读）
        0x59000000,           // 0.20 减弱
        0x00000000,           // 0.38 完全透明（封面干净）
        0x00000000,           // 0.42 仍然透明
        0xFF0F0F0F.toInt(),   // 0.50 封面结束处：不透明
        0xFF0F0F0F.toInt()    // 1.00 到底
    )

    /** 与 [COLORS] **一一对应**的纵向位置（0..1） */
    val OFFSETS = floatArrayOf(0f, 0.20f, 0.38f, 0.42f, 0.50f, 1f)

    /** 封面结束、渐变转为完全不透明的位置 */
    const val OPAQUE_FROM = 0.50f

    init {
        // 双保险：万一将来有人只改了一边，类加载时就失败，
        // 而不是等到用户点到中岛、SystemUI 绘制时才崩溃。
        require(COLORS.size == OFFSETS.size) {
            "渐变的颜色数(${COLORS.size})与位置数(${OFFSETS.size})必须相等，" +
                "否则 GradientDrawable 绘制时会抛异常并崩溃 SystemUI"
        }
    }

    // ==================================================================
    // One UI 样式（封面是"独立卡片"，浮在暗面之上）
    // ==================================================================
    //
    // ============ 设计（用户选项 A）============
    //
    // 参考图（One UI 宣传片中间那台）的背景是**整体压暗**的，卡片像浮在暗面上。
    //
    // 之前是"按卡片位置开一个全透明窗口"，结果是卡片周围露出一大块**高亮壁纸**，
    // 观感很花 —— 而且让人把壁纸的形状误认成"卡片轮廓"（我为此白查了两轮）。
    //
    // 现在改成：**遮罩就是纯背景，不关心卡片在哪**。
    // 配套的结构改动：`scrim` 必须 `addView` 在 `art` **之前**（画在卡片下面），
    // 这样卡片完全不受遮罩影响，背景则整体压暗。
    //
    // 额外好处：停靠点是**常量**，不依赖 cardTop/cardSize ——
    // 少了一整类"传参算错就崩"的风险（上一版就是靠传入的比例算出来的）。
    /**
     * One UI 样式的暗化渐变。
     *
     * ============ 改动（音乐锁屏"整卡"样式的第一步）============
     *
     * 之前是"完全不透明"的 #0F0F0F —— 观感很素（用户反馈"太素了没有质感"）。
     * 现在下面垫了**封面模糊 + 专辑色着色**的背景层，所以渐变要"留出可见度"：
     * 中段只压到 ~85%，让模糊的彩色背景透出来；底部（控制键所在）仍压到实色保证可读。
     *
     * 约束（有单测守着，别破坏）：
     *   · 任何一档都不能完全透明（否则会露出壁纸）
     *   · 第一档 alpha >= 0x66（否则系统时钟看不清）
     *   · 最后一档必须 0xFF（底部控制键可读）
     */
    val COLORS_ONEUI = intArrayOf(
        0x99000000.toInt(),   // 0.00 顶部压暗（时钟可读，仍能透出模糊背景）
        0xB3000000.toInt(),   // 0.32
        0xD9000000.toInt(),   // 0.60 让专辑色的模糊背景可见
        0xFF0F0F0F.toInt(),   // 0.82 起实色（控制键区域）
        0xFF0F0F0F.toInt()    // 1.00
    )

    /** 与 [COLORS_ONEUI] 一一对应 */
    val OFFSETS_ONEUI = floatArrayOf(0f, 0.32f, 0.60f, 0.82f, 1f)

    init {
        require(COLORS_ONEUI.size == OFFSETS_ONEUI.size) {
            "One UI 渐变的颜色数(${COLORS_ONEUI.size})与位置数(${OFFSETS_ONEUI.size})必须相等，" +
                "否则 GradientDrawable 绘制时会抛异常并崩溃 SystemUI"
        }
    }
}
